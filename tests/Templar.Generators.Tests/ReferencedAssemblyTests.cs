    private const string LibSource = "namespace Lib;\n"
        + "using Templar.Rendering;\n"
        + "public interface IShape { string Name { get; } }\n"
        + "[Template(\"Shapes/Circle\")] public sealed record Circle(string Name, int Radius) : IShape;\n"
        + "[Template(\"Shapes/Shape\")] public abstract record Shape(string Name);\n"
        + "[Template(\"Vault\")] public sealed class Vault { internal string Code => \"c\"; }\n"
        + "public sealed record Plain(string Name);\n"
        + "public static class Use { public static string Named(Plain plain) => Compositor.ResolveTemplate(plain, \"Named\"); }\n";

    private static (GeneratorHarness.Run Run, MetadataReference Reference) Lib()
    {
        return Library("Lib",
                       LibSource,
                       Array.Empty<MetadataReference>(),
                       ("/proj/Templates/Shapes/Circle.tpl", "circle \"{{ name }}\" r{{ radius }}"),
                       ("/proj/Templates/Shapes/Shape.tpl", "shape {{ name }}"),
                       ("/proj/Templates/Vault.tpl", "vault {{ code }}"),
                       ("/proj/Templates/Named.tpl", "named {{ name }}"),
                       ("/proj/Templates/Unused.tpl", "never {{ name }}"));
    }

    private static (GeneratorHarness.Run Run, MetadataReference Reference) Library(string name,
                                                                                   string source,
                                                                                   MetadataReference[] references,
                                                                                   params (string Path, string Text)[] templates)
    {
        var compilation = GeneratorHarness.Compile(new[] { source }, references)
            .WithAssemblyName(name);
        var driver = GeneratorHarness.CreateDriver(templates, name);
        var run = GeneratorHarness.Advance(driver, compilation);
        Assert.Empty(run.Diagnostics);
        var reference = Reference(run.Output);
        return (run, reference);
    }

    private static MetadataReference Reference(Compilation compilation)
    {
        using var stream = new MemoryStream();
        var emit = compilation.Emit(stream);
        var problems = emit.Diagnostics.Select(d => d.ToString());
        Assert.True(emit.Success, string.Join("\n", problems));
        return MetadataReference.CreateFromImage(stream.ToArray());
    }

    private static GeneratorHarness.Run Generate(string source,
                                                 MetadataReference[] references,
                                                 params (string Path, string Text)[] templates)
    {
        var compilation = GeneratorHarness.Compile(new[] { source }, references);
        var driver = GeneratorHarness.CreateDriver(templates);
        return GeneratorHarness.Advance(driver, compilation);
    }

    [Fact]
    public void Library_carries_the_text_of_each_template_its_Template_types_name()
    {
        var lib = Lib();

        var expected = "// <auto-generated/>\n"
            + "#nullable enable\n"
            + "\n"
            + "[assembly: global::Templar.Rendering.TemplateTextAttribute(\"Shapes/Circle\", \"circle \\\"{{ name }}\\\" r{{ radius }}\")]\n"
            + "[assembly: global::Templar.Rendering.TemplateTextAttribute(\"Shapes/Shape\", \"shape {{ name }}\")]\n"
            + "[assembly: global::Templar.Rendering.TemplateTextAttribute(\"Vault\", \"vault {{ code }}\")]\n";
        Assert.Equal(expected, lib.Run.Sources["Templar.Templates.g.cs"]);
        var assembly = GeneratorHarness.LoadTogether(lib.Run.Output).Single();
        var carried = assembly.GetCustomAttributes<TemplateTextAttribute>()
            .OrderBy(a => a.Name, StringComparer.Ordinal)
            .Select(a => (a.Name, a.Text))
            .ToArray();
        Assert.Equal(new[]
                     {
                         ("Shapes/Circle", "circle \"{{ name }}\" r{{ radius }}"),
                         ("Shapes/Shape", "shape {{ name }}"),
                         ("Vault", "vault {{ code }}"),
                     },
                     carried);
    }

    [Fact]
    public void Referenced_Template_type_renders_by_the_text_its_assembly_carries()
    {
        var lib = Lib();
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Card\")] public sealed record Card(Lib.Circle Main); "
            + "public static class Probe { "
            + "public static string Run() => Compositor.ResolveTemplate(new Card(new Lib.Circle(\"a\", 1))); "
            + "public static string Root() => Compositor.ResolveTemplate(new Lib.Circle(\"a\", 1)); }";

        var run = Generate(source, new[] { lib.Reference }, ("/proj/Templates/Card.tpl", "card {{ main }}"));

        Assert.Empty(run.Diagnostics);
        var circle = run.Sources["Lib.Shapes.Circle.g.cs"];
        Assert.Contains("namespace App.Templates.Lib.Shapes;", circle);
        Assert.Contains("internal static class Lib_Shapes_CircleTemplate", circle);
        Assert.Contains("Steps(global::Templar.Rendering.TemplarWriter w, global::Lib.Circle model)", circle);
        Assert.Contains("        yield return w.Compose(model.Main, global::App.Templates.Lib.Shapes.Lib_Shapes_CircleTemplate.Steps);\n",
                        run.Sources["Card.g.cs"]);
        Assert.Contains("            return global::Templar.Rendering.TemplarWriter.Render(model, global::App.Templates.Lib.Shapes.Lib_Shapes_CircleTemplate.Steps, options);\n",
                        run.Sources["Templar.Interceptors.g.cs"]);
        var app = GeneratorHarness.LoadTogether(lib.Run.Output, run.Output).Last();
        Assert.Equal("card circle \"a\" r1", GeneratorHarness.Probe(app, "Run"));
        Assert.Equal("circle \"a\" r1", GeneratorHarness.Probe(app, "Root"));
    }

    [Fact]
    public void Referenced_template_compiles_beside_this_projects_template_of_the_same_name()
    {
        var lib = Lib();
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Shapes/Circle\")] public sealed record Ring(string Name); "
            + "[Template(\"Card\")] public sealed record Card(Lib.Circle Main, Ring Other); "
            + "public static class Probe { "
            + "public static string Run() => Compositor.ResolveTemplate(new Card(new Lib.Circle(\"a\", 1), new Ring(\"b\"))); }";

        var run = Generate(source,
                           new[] { lib.Reference },
                           ("/proj/Templates/Card.tpl", "{{ main }}|{{ other }}"),
                           ("/proj/Templates/Shapes/Circle.tpl", "ring {{ name }}"));

        Assert.Empty(run.Diagnostics);
        var own = run.Sources["Shapes.Circle.g.cs"];
        Assert.Contains("namespace App.Templates.Shapes;", own);
        Assert.Contains("internal static class CircleTemplate", own);
        Assert.Contains("Steps(global::Templar.Rendering.TemplarWriter w, global::App.Ring model)", own);
        var carried = run.Sources["Lib.Shapes.Circle.g.cs"];
        Assert.Contains("namespace App.Templates.Lib.Shapes;", carried);
        Assert.Contains("internal static class Lib_Shapes_CircleTemplate", carried);
        Assert.Contains("Steps(global::Templar.Rendering.TemplarWriter w, global::Lib.Circle model)", carried);
        var card = run.Sources["Card.g.cs"];
        Assert.Contains("        yield return w.Compose(model.Main, global::App.Templates.Lib.Shapes.Lib_Shapes_CircleTemplate.Steps);\n", card);
        Assert.Contains("        yield return w.Compose(model.Other, global::App.Templates.Shapes.CircleTemplate.Steps);\n", card);
        var expected = "// <auto-generated/>\n"
            + "#nullable enable\n"
            + "\n"
            + "[assembly: global::Templar.Rendering.TemplateTextAttribute(\"Card\", \"{{ main }}|{{ other }}\")]\n"
            + "[assembly: global::Templar.Rendering.TemplateTextAttribute(\"Shapes/Circle\", \"ring {{ name }}\")]\n";
        Assert.Equal(expected, run.Sources["Templar.Templates.g.cs"]);
        var app = GeneratorHarness.LoadTogether(lib.Run.Output, run.Output).Last();
        Assert.Equal("circle \"a\" r1|ring b", GeneratorHarness.Probe(app, "Run"));
    }

    [Fact]
    public void Declared_type_of_a_referenced_assembly_collects_its_subtypes_there_and_here()
    {
        var lib = Lib();
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Square\")] public sealed record Square(string Name, int Side) : Lib.IShape; "
            + "[Template(\"Drawing\")] public sealed record Drawing(Sequence<Lib.IShape> Shapes); "
            + "public static class Probe { "
            + "public static string Run() => Compositor.ResolveTemplate(new Drawing(Sequence.CommaList<Lib.IShape>([new Lib.Circle(\"a\", 1), new Square(\"b\", 2)]))); }";

        var run = Generate(source,
                           new[] { lib.Reference },
                           ("/proj/Templates/Drawing.tpl", "{{ shapes }}"),
                           ("/proj/Templates/Square.tpl", "square {{ name }} s{{ side }}"));

        Assert.Empty(run.Diagnostics);
        var resolvers = run.Sources["Templar.Resolvers.g.cs"];
        Assert.Contains("internal static class Lib_IShapeResolver", resolvers);
        Assert.Contains("            global::App.Square m => global::App.Templates.SquareTemplate.Steps(w, m),\n", resolvers);
        Assert.Contains("            global::Lib.Circle m => global::App.Templates.Lib.Shapes.Lib_Shapes_CircleTemplate.Steps(w, m),\n", resolvers);
        var app = GeneratorHarness.LoadTogether(lib.Run.Output, run.Output).Last();
        Assert.Equal("circle \"a\" r1, square b s2", GeneratorHarness.Probe(app, "Run"));
    }

    [Fact]
    public void Subtype_here_of_a_referenced_type_renders_by_the_template_of_its_base()
    {
        var lib = Lib();
        var source = "namespace App; using Templar.Rendering; "
            + "public sealed record Dot(string Name) : Lib.Shape(Name); "
