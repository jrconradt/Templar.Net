    }

    [Fact]
    public void Spots_of_a_referenced_template_reach_the_assemblies_its_types_come_from()
    {
        var kit = Library("Kit",
                          "namespace Kit; using Templar.Rendering; [Template(\"Badge\")] public sealed record Badge(string Label);",
                          Array.Empty<MetadataReference>(),
                          ("/proj/Templates/Badge.tpl", "badge {{ label }}"));
        var mid = Library("Mid",
                          "namespace Mid; using Templar.Rendering; [Template(\"Frame\")] public sealed record Frame(Kit.Badge Badge);",
                          new[] { kit.Reference },
                          ("/proj/Templates/Frame.tpl", "frame {{ badge }}"));
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Card\")] public sealed record Card(Mid.Frame Main); "
            + "public static class Probe { "
            + "public static string Run() => Compositor.ResolveTemplate(new Card(new Mid.Frame(new Kit.Badge(\"x\")))); }";

        var run = Generate(source, new[] { mid.Reference, kit.Reference }, ("/proj/Templates/Card.tpl", "{{ main }}"));

        Assert.Contains("Kit.Badge.g.cs", mid.Run.Sources.Keys);
        Assert.Empty(run.Diagnostics);
        Assert.Contains("Mid.Frame.g.cs", run.Sources.Keys);
        Assert.Contains("Kit.Badge.g.cs", run.Sources.Keys);
        var app = GeneratorHarness.LoadTogether(kit.Run.Output, mid.Run.Output, run.Output).Last();
        Assert.Equal("frame badge x", GeneratorHarness.Probe(app, "Run"));
    }

    [Fact]
    public void Referenced_pair_is_checked_here_and_reports_TMPLR006()
    {
        var lib = Lib();
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Card\")] public sealed record Card(Lib.Vault Main);";

        var run = Generate(source, new[] { lib.Reference }, ("/proj/Templates/Card.tpl", "{{ main }}"));

        var diagnostic = Assert.Single(run.Diagnostics);
        Assert.Equal("TMPLR006", diagnostic.Id);
        Assert.Equal("Spot 'code' at line 1 of template 'Vault' names no readable property of 'Lib.Vault'", diagnostic.GetMessage());
        Assert.Equal(new LinePosition(0, source.IndexOf("Template(\"Card\")", StringComparison.Ordinal)), diagnostic.Location.GetLineSpan().StartLinePosition);
    }

    [Fact]
    public void Subtype_here_with_no_Template_reports_TMPLR008_naming_it()
    {
        var lib = Lib();
        var source = "namespace App; using Templar.Rendering; "
            + "public sealed record Square(string Name) : Lib.IShape; "
            + "[Template(\"Card\")] public sealed record Card(Lib.IShape Main);";

        var run = Generate(source, new[] { lib.Reference }, ("/proj/Templates/Card.tpl", "{{ main }}"));

        var diagnostic = Assert.Single(run.Diagnostics);
        Assert.Equal("TMPLR008", diagnostic.Id);
        Assert.Equal("Type 'Lib.IShape' cannot render at spot 'main' (line 1 of template 'Card', property 'Main'): its subtype 'App.Square' has no [Template]",
                     diagnostic.GetMessage());
    }

    [Fact]
    public void Template_type_whose_assembly_carries_no_text_reports_TMPLR008()
    {
        var stamp = GeneratorHarness.Compile(new[] { "namespace Old; using Templar.Rendering; [Template(\"Stamp\")] public sealed record Stamp(string Name);" })
            .WithAssemblyName("Old");
        var old = Reference(stamp);
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Card\")] public sealed record Card(Old.Stamp Main);";

        var run = Generate(source, new[] { old }, ("/proj/Templates/Card.tpl", "{{ main }}"));

        var diagnostic = Assert.Single(run.Diagnostics);
        Assert.Equal("TMPLR008", diagnostic.Id);
        Assert.Equal("Type 'Old.Stamp' cannot render at spot 'main' (line 1 of template 'Card', property 'Main'): its [Template] is declared in assembly 'Old', which carries no text for template 'Stamp'",
                     diagnostic.GetMessage());
    }

    [Fact]
    public void Subtype_a_third_assembly_declares_is_not_collected_and_throws_at_run_time()
    {
        var lib = Lib();
        var ext = Library("Ext",
                          "namespace Ext; using Templar.Rendering; [Template(\"Hex\")] public sealed record Hex(string Name) : Lib.IShape;",
                          new[] { lib.Reference },
                          ("/proj/Templates/Hex.tpl", "hex {{ name }}"));
        var source = "namespace App; using Templar.Rendering; "
            + "[Template(\"Square\")] public sealed record Square(string Name, int Side) : Lib.IShape; "
            + "[Template(\"Card\")] public sealed record Card(Lib.IShape Main); "
            + "public static class Probe { "
            + "public static string Run() => Compositor.ResolveTemplate(new Card(new Square(\"b\", 2))); "
            + "public static string Third() => Compositor.ResolveTemplate(new Card(new Ext.Hex(\"h\"))); }";

        var run = Generate(source,
                           new[] { lib.Reference, ext.Reference },
                           ("/proj/Templates/Card.tpl", "{{ main }}"),
                           ("/proj/Templates/Square.tpl", "square {{ name }} s{{ side }}"));

        Assert.Empty(run.Diagnostics);
        Assert.DoesNotContain("Ext.Hex", run.Sources["Templar.Resolvers.g.cs"]);
        var app = GeneratorHarness.LoadTogether(lib.Run.Output, ext.Run.Output, run.Output).Last();
        Assert.Equal("square b s2", GeneratorHarness.Probe(app, "Run"));
        var thrown = Assert.Throws<InvalidOperationException>(() => GeneratorHarness.Probe(app, "Third"));
        Assert.Equal("Type 'Ext.Hex' was not resolved for 'Lib.IShape' at compile time.", thrown.Message);
    }
