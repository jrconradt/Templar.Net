using System.Reflection;
using Templar.Presets;
using Xunit;

namespace Templar.Tests;

public class CSharpFileTests
{
    [Fact]
    public void RendersHeaderUsingsNamespaceBody()
    {
        var file = new CSharpFile
        {
            Namespace = "Acme.Generated",
            Usings = new[] { "System", "System.Linq" },
            Body = "public sealed class Foo;"
        };

        var output = file.Render();

        Assert.Contains("#nullable enable", output);
        Assert.Contains("using System;", output);
        Assert.Contains("using System.Linq;", output);
        Assert.Contains("namespace Acme.Generated;", output);
        Assert.Contains("public sealed class Foo;", output);
    }

    [Fact]
    public void EmptyUsingsRendersBlankBlock()
    {
        var file = new CSharpFile
        {
            Namespace = "Empty",
            Body = "// nothing"
        };

        var output = file.Render();

        Assert.DoesNotContain("using ", output);
        Assert.Contains("namespace Empty;", output);
    }

    [Fact]
    public void PragmasEmittedBetweenHeaderAndUsings()
    {
        var file = new CSharpFile
        {
            Namespace = "X",
            Pragmas = "#pragma warning disable CS8618",
            Usings = new[] { "System" },
            Body = "class C;"
        };

        var output = file.Render();
        var pragmaIdx = output.IndexOf("#pragma warning");
        var usingIdx = output.IndexOf("using System;");
        var nsIdx = output.IndexOf("namespace X;");

        Assert.True(pragmaIdx > 0);
        Assert.True(pragmaIdx < usingIdx, "pragmas come before usings");
        Assert.True(usingIdx < nsIdx, "usings come before namespace");
    }

    [Fact]
    public void CustomHeaderOverridesDefault()
    {
        var file = new CSharpFile
        {
            Header = "// CUSTOM HEADER",
            Namespace = "X",
            Body = "class C;"
        };

        var output = file.Render();
        Assert.Contains("// CUSTOM HEADER", output);
        Assert.DoesNotContain("<auto-generated", output);
    }

    // Expected text captured from Templar.Net 0.2.0 (98b5955) rendering the same inputs with default options.
    public static TheoryData<string, CSharpFile, string> Rendered020 => new()
    {
        {
            "UsingsAndBody",
            new CSharpFile { Namespace = "Acme.Generated", Usings = new[] { "System", "System.Linq" }, Body = "public sealed class Foo;" },
            "#nullable enable\nusing System;\nusing System.Linq;\n\nnamespace Acme.Generated;\n\npublic sealed class Foo;"
        },
        {
            "NoUsings",
            new CSharpFile { Namespace = "Empty", Body = "// nothing" },
            "#nullable enable\n\nnamespace Empty;\n\n// nothing"
        },
        {
            "Pragmas",
            new CSharpFile { Namespace = "X", Pragmas = "#pragma warning disable CS8618", Usings = new[] { "System" }, Body = "class C;" },
            "#nullable enable\n#pragma warning disable CS8618\nusing System;\n\nnamespace X;\n\nclass C;"
        },
        {
            "CustomHeader",
            new CSharpFile { Header = "// CUSTOM HEADER", Namespace = "X", Body = "class C;" },
            "// CUSTOM HEADER\n\nnamespace X;\n\nclass C;"
        },
        {
            "Defaults",
            new CSharpFile(),
            "#nullable enable\n\nnamespace ;\n\n"
        },
        {
            "MultiLine",
            new CSharpFile
            {
                Header = "// <auto-generated/>\n#nullable enable",
                Pragmas = "#pragma warning disable CS1591\n#pragma warning disable CS8618",
                Usings = new[] { "System", "System.Collections.Generic", "System.Linq" },
                Namespace = "Acme.Deep",
                Body = "public sealed class Foo\n{\n    public int X { get; }\n\n    public void M()\n    {\n        return;\n    }\n}\n",
            },
            "// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n#pragma warning disable CS8618\nusing System;\nusing System.Collections.Generic;\nusing System.Linq;\n\nnamespace Acme.Deep;\n\npublic sealed class Foo\n{\n    public int X { get; }\n    public void M()\n    {\n        return;\n    }\n}\n"
        },
        {
            "EmptyHeader",
            new CSharpFile { Header = "", Namespace = "N", Usings = new[] { "A" }, Body = "" },
            "using A;\n\nnamespace N;\n\n"
        },
    };

    [Theory]
    [MemberData(nameof(Rendered020))]
    public void Renders_byte_identical_to_0_2_0(string name, CSharpFile file, string expected)
    {
        Assert.False(string.IsNullOrEmpty(name));
        Assert.Equal(expected, file.Render());
    }

    [Theory]
    [InlineData(typeof(CSharpFile))]
    [InlineData(typeof(Using))]
    public void Preset_is_a_sealed_plain_type_with_non_virtual_members(Type type)
    {
        Assert.True(type.IsSealed);
        Assert.Equal(typeof(object), type.BaseType);
        var virtuals = type.GetMethods(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.DeclaredOnly)
            .Where(m => m.IsVirtual)
            .Select(m => m.Name);
        Assert.Empty(virtuals);
    }
}
